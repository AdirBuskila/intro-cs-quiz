# -*- coding: utf-8 -*-
"""Authoring source of the guided course `recursion` (intro-cs).
author.py turns LEVELS into courses/recursion/C01.js ... C10.js ; check.py recompiles every shown snippet with
clang and asserts every stored answer using CHK (the per-question run recipe).
"""
import html

CID = "recursion"
LEVELS = []
CHK = {}


def esc(code):
    return html.escape(code.strip("\n"), quote=False)


def pre(code):
    return "<pre><code>" + esc(code) + "</code></pre>"


def fence(code):
    return "```c\n" + code.strip("\n") + "\n```"


def mcq(qid, text, opts, ok, expl, recap, chk=None):
    q = {"id": qid, "question": text,
         "options": [{"id": "abcdefgh"[i], "value": v} for i, v in enumerate(opts)],
         "correctId": "abcdefgh"[ok], "explanation": expl, "recap": recap}
    if chk:
        CHK[qid] = chk
    return q


def step(qid, st, recap, chk=None):
    if chk:
        CHK[qid] = chk
    return {"id": qid, "step": st, "recap": recap}


def numeric(qid, prompt, answer, explain, recap, chk):
    return step(qid, {"type": "numeric", "prompt": prompt, "answer": answer, "tol": 0, "explain": explain}, recap, chk)


def order(qid, prompt, lines, explain, recap, chk):
    return step(qid, {"type": "order", "prompt": prompt, "lines": lines, "code": True, "explain": explain}, recap, chk)


def findbug(qid, prompt, lines, bug, explain, recap, chk):
    return step(qid, {"type": "findbug", "prompt": prompt, "lines": lines, "bugIndex": bug, "code": True,
                      "explain": explain}, recap, chk)


def fillblank(qid, prompt, lines, blank, opts, ok, explain, recap, chk):
    return step(qid, {"type": "fillblank", "prompt": prompt, "lines": lines, "blankIndex": blank, "code": True,
                      "options": [{"id": "abcdefgh"[i], "value": v} for i, v in enumerate(opts)],
                      "correctId": "abcdefgh"[ok], "explain": explain}, recap, chk)


def level(order_, icon, title, goal, lesson, questions, boss=False):
    LEVELS.append({"id": "C%02d" % order_, "order": order_, "icon": icon, "title": title, "goal": goal,
                   "boss": boss, "source": "ai-verified", "lesson": {"html": lesson}, "questions": questions})


def seq(*a):
    return " ".join(str(x) for x in a)


